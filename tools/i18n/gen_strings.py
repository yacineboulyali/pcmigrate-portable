# Generates src/strings.h from tools/i18n/strings.py
import os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from strings import S
root = os.path.join(os.path.dirname(__file__), "..", "..")
def c(s): return 'L"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'
ph = re.compile(r"%(?:ls|lu|d|08lX|\.\d+f)")
ids = set()
for row in S:
    assert len(row) == 5, row[0]
    assert row[0] not in ids, row[0]; ids.add(row[0])
    base = ph.findall(row[1])
    for t in row[2:]:
        assert ph.findall(t) == base, (row[0], t)
out = ["// AUTO-GENERATED by tools/i18n/gen_strings.py from tools/i18n/strings.py - do not edit by hand.",
       "#pragma once", "enum Lang { L_EN = 0, L_FR, L_AR, L_ES, L_COUNT };",
       "static const wchar_t* const kLangNames[L_COUNT] = {L\"English\", L\"Fran\\u00e7ais\", L\"\\u0627\\u0644\\u0639\\u0631\\u0628\\u064a\\u0629\", L\"Espa\\u00f1ol\"};",
       "static const wchar_t* const kLangCodes[L_COUNT] = {L\"en\", L\"fr\", L\"ar\", L\"es\"};",
       "enum StrId {"] + [f"    {r[0]}," for r in S] + ["    S__COUNT", "};",
       "static const wchar_t* const kStrings[S__COUNT][L_COUNT] = {"]
for r in S:
    out.append("    {" + ", ".join(c(t) for t in r[1:]) + "},")
out += ["};", ""]
open(os.path.join(root, "src", "strings.h"), "w", encoding="utf-8").write("\n".join(out))
print(len(S), "strings x 4 languages -> src/strings.h")
